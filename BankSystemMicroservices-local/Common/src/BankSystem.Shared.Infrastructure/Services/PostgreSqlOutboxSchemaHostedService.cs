using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;

namespace BankSystem.Shared.Infrastructure.Services;

/// <summary>
/// Adds MassTransit's Entity Framework outbox tables to an existing PostgreSQL database.
/// EnsureCreated only creates a schema for a new database; it does not add tables
/// when that database already exists.
/// </summary>
public sealed class PostgreSqlOutboxSchemaHostedService<TContext>(IServiceScopeFactory scopeFactory)
    : IHostedService
    where TContext : DbContext
{
    public async Task StartAsync(CancellationToken cancellationToken)
    {
        await using var scope = scopeFactory.CreateAsyncScope();
        var database = scope.ServiceProvider.GetRequiredService<TContext>().Database;

        if (!string.Equals(
                database.ProviderName,
                "Npgsql.EntityFrameworkCore.PostgreSQL",
                StringComparison.Ordinal))
        {
            return;
        }

        await database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS "InboxState" (
                "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "MessageId" uuid NOT NULL,
                "ConsumerId" uuid NOT NULL,
                "LockId" uuid NOT NULL,
                "RowVersion" bytea NULL,
                "Received" timestamp with time zone NOT NULL,
                "ReceiveCount" integer NOT NULL,
                "ExpirationTime" timestamp with time zone NULL,
                "Consumed" timestamp with time zone NULL,
                "Delivered" timestamp with time zone NULL,
                "LastSequenceNumber" bigint NULL,
                CONSTRAINT "AK_InboxState_MessageId_ConsumerId" UNIQUE ("MessageId", "ConsumerId")
            );
            """, cancellationToken);

        await database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS "OutboxState" (
                "OutboxId" uuid PRIMARY KEY,
                "LockId" uuid NOT NULL,
                "RowVersion" bytea NULL,
                "Created" timestamp with time zone NOT NULL,
                "Delivered" timestamp with time zone NULL,
                "LastSequenceNumber" bigint NULL
            );
            """, cancellationToken);

        await database.ExecuteSqlRawAsync("""
            CREATE TABLE IF NOT EXISTS "OutboxMessage" (
                "SequenceNumber" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "EnqueueTime" timestamp with time zone NULL,
                "SentTime" timestamp with time zone NOT NULL,
                "Headers" text NULL,
                "Properties" text NULL,
                "InboxMessageId" uuid NULL,
                "InboxConsumerId" uuid NULL,
                "OutboxId" uuid NULL,
                "MessageId" uuid NOT NULL,
                "ContentType" character varying(256) NOT NULL,
                "MessageType" text NOT NULL,
                "Body" text NOT NULL,
                "ConversationId" uuid NULL,
                "CorrelationId" uuid NULL,
                "InitiatorId" uuid NULL,
                "RequestId" uuid NULL,
                "SourceAddress" character varying(256) NULL,
                "DestinationAddress" character varying(256) NULL,
                "ResponseAddress" character varying(256) NULL,
                "FaultAddress" character varying(256) NULL,
                "ExpirationTime" timestamp with time zone NULL,
                CONSTRAINT "FK_OutboxMessage_InboxState_InboxMessageId_InboxConsumerId"
                    FOREIGN KEY ("InboxMessageId", "InboxConsumerId")
                    REFERENCES "InboxState" ("MessageId", "ConsumerId"),
                CONSTRAINT "FK_OutboxMessage_OutboxState_OutboxId"
                    FOREIGN KEY ("OutboxId") REFERENCES "OutboxState" ("OutboxId")
            );
            """, cancellationToken);

        await database.ExecuteSqlRawAsync("""
            CREATE INDEX IF NOT EXISTS "IX_InboxState_Delivered" ON "InboxState" ("Delivered");
            CREATE INDEX IF NOT EXISTS "IX_OutboxMessage_EnqueueTime" ON "OutboxMessage" ("EnqueueTime");
            CREATE INDEX IF NOT EXISTS "IX_OutboxMessage_ExpirationTime" ON "OutboxMessage" ("ExpirationTime");
            CREATE UNIQUE INDEX IF NOT EXISTS "IX_OutboxMessage_InboxMessageId_InboxConsumerId_SequenceNumber"
                ON "OutboxMessage" ("InboxMessageId", "InboxConsumerId", "SequenceNumber");
            CREATE UNIQUE INDEX IF NOT EXISTS "IX_OutboxMessage_OutboxId_SequenceNumber"
                ON "OutboxMessage" ("OutboxId", "SequenceNumber");
            CREATE INDEX IF NOT EXISTS "IX_OutboxState_Created" ON "OutboxState" ("Created");
            """, cancellationToken);
    }

    public Task StopAsync(CancellationToken cancellationToken) => Task.CompletedTask;
}
